// Jellyfin and Emby name a studio or a person by core.FacetID, a hash of the
// value. Resolving one (StudioIds=, PersonIds=) inverted the hash by listing
// and hashing every studio of the library, or every credited person.
//
// catalog_facet_ids keeps the inverse under its primary key: every studio
// and credited person the vocabularies (catalog_studio_names,
// catalog_person_names) have held, by identifier. Triggers stay plain SQL,
// so they cannot hash: a new vocabulary row, written by this binary or an
// older one, is appended to catalog_facet_id_queue, and the catalogue's fold
// loop gives it its identifier (nameQueuedFacets). A lookup that misses also
// hashes the queue, the last few seconds' new values, so it is exact
// straight after an ingest. A whole vocabulary (the migration, a restore, a
// bulk fixture) is named in identifier order, so the index is appended to
// rather than written at random.

// facetVocab is a vocabulary whose values have identifiers.
type facetVocab struct {
	table, key, kind string // table, its value column, the core.FacetID kind
	count, keyType   string // its per-value title or credit count; the key's type
}

var (
	studioVocab = facetVocab{"catalog_studio_names", "studio", "studio", "titles", "TEXT"}
	personVocab = facetVocab{"catalog_person_names", "person_tmdb", "person", "credits", "BIGINT"}
	facetVocabs = []facetVocab{studioVocab, personVocab}
)

func init() {
	queue := func(v facetVocab) string {
		return `INSERT INTO catalog_facet_id_queue(kind,value) VALUES ('` + v.kind + `',CAST(NEW.` + v.key + ` AS TEXT));`
	}
	sqlite := []string{
		`CREATE TABLE catalog_facet_ids(id TEXT PRIMARY KEY, kind TEXT NOT NULL, value TEXT NOT NULL) WITHOUT ROWID`,
		`CREATE TABLE catalog_facet_id_queue(seq INTEGER PRIMARY KEY, kind TEXT NOT NULL, value TEXT NOT NULL)`,
	}
	// The lock keeps vocabulary writers (of this or an older Ether) out
	// until the backfill and the triggers are visible together.
	pg := []string{
		`LOCK TABLE catalog_studio_names, catalog_person_names IN SHARE ROW EXCLUSIVE MODE`,
		`CREATE TABLE catalog_facet_ids(id TEXT PRIMARY KEY, kind TEXT NOT NULL, value TEXT NOT NULL)`,
		`CREATE TABLE catalog_facet_id_queue(seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind TEXT NOT NULL, value TEXT NOT NULL)`,
	}
	for _, v := range facetVocabs {
		sqlite = append(sqlite, `CREATE TRIGGER `+v.table+`_facet_id AFTER INSERT ON `+v.table+` BEGIN `+queue(v)+` END`)
		pg = append(pg,
			`CREATE FUNCTION `+v.table+`_facet_id() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN `+queue(v)+` RETURN NULL; END $$`,
			`CREATE TRIGGER `+v.table+`_facet_id AFTER INSERT ON `+v.table+` FOR EACH ROW EXECUTE FUNCTION `+v.table+`_facet_id()`)
	}
	store.Register("catalog", 54, strings.Join(sqlite, ";\n")+";")
	store.RegisterDialect("catalog", 54, store.Postgres, strings.Join(pg, ";\n")+";")
	apply := func(ddl []string) func(context.Context, *sql.Tx) error {
		return func(ctx context.Context, tx *sql.Tx) error {
			for _, q := range ddl {
				if _, err := tx.ExecContext(ctx, q); err != nil {
					return err
				}
			}
			return rebuildFacetIDs(ctx, tx)
		}
	}
	store.RegisterSQLiteApply("catalog", 54, apply(sqlite))
	store.RegisterPostgresApply("catalog", 54, apply(pg))
	// Both are derived from the vocabularies alone: a dump leaves them out
	// and a restore names the restored vocabularies whole.
	store.RegisterLocalTable("catalog_facet_ids")
	store.RegisterLocalTable("catalog_facet_id_queue")
	store.RegisterRestore("catalog_facet_ids", func(context.Context, *sql.Tx) (func(context.Context, *sql.Tx) error, error) {
		return func(ctx context.Context, tx *sql.Tx) error { return rebuildFacetIDs(ctx, tx) }, nil
	}, "catalog_facet_ids", "catalog_facet_id_queue")
}

type queryExecer interface {
	execer
	QueryContext(ctx context.Context, query string, args ...any) (*sql.Rows, error)
}

// facetIDBatch bounds the rows of one insert and of one queue batch.
const facetIDBatch = 500

type facetIDRow struct {
	id          [16]byte
	kind, value string
}

func facetIDOf(kind, value string) facetIDRow {
	r := facetIDRow{kind: kind, value: value}
	_, _ = hex.Decode(r.id[:], []byte(core.FacetID(kind, value)))
	return r
}

// insertFacetIDs writes rows in identifier order.
func insertFacetIDs(ctx context.Context, db execer, rows []facetIDRow) error {
	slices.SortFunc(rows, func(a, b facetIDRow) int { return bytes.Compare(a.id[:], b.id[:]) })
	for start := 0; start < len(rows); start += facetIDBatch {
		part := rows[start:min(start+facetIDBatch, len(rows))]
		args := make([]any, 0, 3*len(part))
		for _, r := range part {
			args = append(args, hex.EncodeToString(r.id[:]), r.kind, r.value)
		}
		if _, err := db.ExecContext(ctx, `INSERT INTO catalog_facet_ids(id,kind,value) VALUES `+valueRows(len(part), 3)+` ON CONFLICT(id) DO NOTHING`, args...); err != nil {
			return err
		}
	}
	return nil
}

// rebuildFacetIDs names every value the vocabularies hold, whole: the
// migration, a restore and a bulk load, whose vocabulary writes the queue
// trigger may not have seen.
func rebuildFacetIDs(ctx context.Context, db queryExecer) error {
	for _, q := range []string{`DELETE FROM catalog_facet_id_queue`, `DELETE FROM catalog_facet_ids`} {
		if _, err := db.ExecContext(ctx, q); err != nil {
			return err
		}
	}
	for _, v := range facetVocabs {
		rows, err := db.QueryContext(ctx, `SELECT CAST(`+v.key+` AS TEXT) FROM `+v.table)
		if err != nil {
			return err
		}
		var out []facetIDRow
		for rows.Next() {
			var value string
			if err := rows.Scan(&value); err != nil {
				rows.Close()
				return err
			}
			out = append(out, facetIDOf(v.kind, value))
		}
		err = rows.Err()
		rows.Close()
		if err != nil {
			return err
		}
		if err := insertFacetIDs(ctx, db, out); err != nil {
			return err
		}
	}
	return nil
}

// nameQueuedFacets gives the queued values their identifiers, one bounded
// batch per transaction, and reports how many it named.
func (c *Catalog) nameQueuedFacets(ctx context.Context) (int, error) {
	named := 0
	for ctx.Err() == nil {
		n, err := c.nameQueueBatch(ctx)
		named += n
		if err != nil || n < facetIDBatch {
			return named, err
		}
	}
	return named, ctx.Err()
}

func (c *Catalog) nameQueueBatch(ctx context.Context) (int, error) {
	tx, err := c.db.BeginTx(ctx, nil)
	if err != nil {
		return 0, err
	}
	defer tx.Rollback()
	rows, err := tx.QueryContext(ctx, `SELECT seq, kind, value FROM catalog_facet_id_queue ORDER BY seq LIMIT ?`, facetIDBatch)
	if err != nil {
		return 0, err
	}
	var batch []facetIDRow
	var last int64
	for rows.Next() {
		var kind, value string
		if err := rows.Scan(&last, &kind, &value); err != nil {
			rows.Close()
			return 0, err
		}
		batch = append(batch, facetIDOf(kind, value))
	}
	err = rows.Err()
	rows.Close()
	if err != nil || len(batch) == 0 {
		return 0, err
	}
	if err := insertFacetIDs(ctx, tx, batch); err != nil {
		return 0, err
	}
	// Two nodes may name the same rows; the insert ignores the repeat.
	if _, err := tx.ExecContext(ctx, `DELETE FROM catalog_facet_id_queue WHERE seq<=?`, last); err != nil {
		return 0, err
	}
	return len(batch), tx.Commit()
}

// facetByID is the value of v whose identifier is id and which a title or
// credit still carries.
func (c *Catalog) facetByID(ctx context.Context, v facetVocab, id string) (string, bool, error) {
	var value string
	err := c.db.QueryRowContext(ctx, `SELECT value FROM catalog_facet_ids WHERE id=? AND kind=?`, id, v.kind).Scan(&value)
	if errors.Is(err, sql.ErrNoRows) {
		// Not named yet: stored since the fold loop last ran.
		if value, err = c.queuedFacet(ctx, v, id); err != nil || value == "" {
			return "", false, err
		}
	} else if err != nil {
		return "", false, err
	}
	var key any = value
	if v.keyType == "BIGINT" {
		if key, err = strconv.ParseInt(value, 10, 64); err != nil {
			return "", false, err
		}
	}
	var carried int
	err = c.db.QueryRowContext(ctx, `SELECT COUNT(*) FROM `+v.table+` WHERE `+v.key+`=? AND `+v.count+`>0`, key).Scan(&carried)
	if err != nil || carried == 0 {
		return "", false, err
	}
	return value, true, nil
}

// queuedFacet is the queued value of v whose identifier is id, or "".
func (c *Catalog) queuedFacet(ctx context.Context, v facetVocab, id string) (string, error) {
	rows, err := c.db.QueryContext(ctx, `SELECT value FROM catalog_facet_id_queue WHERE kind=?`, v.kind)
	if err != nil {
		return "", err
	}
	defer rows.Close()
	for rows.Next() {
		var value string
		if err := rows.Scan(&value); err != nil {
			return "", err
		}
		if core.FacetID(v.kind, value) == id {
			return value, nil
		}
	}
	return "", rows.Err()
}

// StudioByFacetID is the stored studio whose core.FacetID("studio", name)
// is id, read by index; ok is false when no title carries such a studio.
func (c *Catalog) StudioByFacetID(ctx context.Context, id string) (string, bool, error) {
	return c.facetByID(ctx, studioVocab, id)
}

// PersonByFacetID is the credited person whose core.FacetID("person",
// tmdb) is id, read by index; ok is false when no credit names such a
// person.
func (c *Catalog) PersonByFacetID(ctx context.Context, id string) (int64, bool, error) {
	k, ok, err := c.facetByID(ctx, personVocab, id)
	if err != nil || !ok {
		return 0, false, err
	}
	tmdb, err := strconv.ParseInt(k, 10, 64)
	if err != nil {
		return 0, false, err
	}
	return tmdb, true, nil
}

#!/usr/bin/env python3
"""Render preserved baseline JSON; never contact, start, or modify a server."""
import argparse
import hashlib
import json
from pathlib import Path


def render(paths):
    targets = []
    order = []
    for label, path in paths:
        rows = {}
        if path is not None:
            raw = path.read_bytes()
            data = json.loads(raw)
            for row in data["rows"]:
                key = (row["client"], row["step"])
                if key in rows:
                    raise ValueError(f"duplicate step in {label}: {key}")
                rows[key] = row
                if key not in order:
                    order.append(key)
            digest = hashlib.sha256(raw).hexdigest()
        else:
            digest = "pending; no artifact supplied"
        targets.append((label, rows, digest))
    print("# PMS / Ether measured comparison\n")
    print("Generated by `scripts/pms-baseline/comparison.py`. Missing artifacts are pending, not zero or passing. "
          "These tables do not certify source provenance or release acceptance. See `README.md`.\n")
    for label, _, digest in targets:
        print(f"- {label}: {digest}")
    metrics = [
        ("Cold latency (ms)", lambda r: f'{r["cold"] / 1e6:.3f}' if r["cold"] else "not measured"),
        ("Warm p50 / p95 (ms)", lambda r: f'{r["warmP50"] / 1e6:.3f} / {r["warmP95"] / 1e6:.3f}'),
        ("CPU cold / warm median (ms)", lambda r: (f'{r["coldCpu"] / 1e6:.3f}' if r["cold"] else "not measured") + f' / {r["warmCpuMedian"] / 1e6:.3f}'),
        ("Block reads / writes, cold (bytes)", lambda r: f'{r["coldReadBytes"]} / {r["coldWriteBytes"]}' if r["cold"] else "not measured"),
        ("Block reads / writes, warm median (bytes)", lambda r: f'{r["warmReadBytesMedian"]} / {r["warmWriteBytesMedian"]}'),
        ("Response raw / gzip / wire (bytes)", lambda r: f'{r["bytes"]} / {r["gzipBytes"]} / {r["wireBytes"]}'),
        ("Items / total; warm samples", lambda r: f'{r["items"]} / {r["totalSize"]}; n={r["warmN"]}'),
    ]
    for title, value in metrics:
        print(f"\n## {title}\n")
        print("| Client / step | " + " | ".join(t[0] for t in targets) + " |")
        print("|---|" + "---|" * len(targets))
        for key in order:
            cells = []
            for _, rows, _ in targets:
                r = rows.get(key)
                if r is None:
                    cell = "pending"
                elif r.get("skipped"):
                    cell = "skipped"
                elif r.get("error") or r["status"] != 200:
                    cell = f'HTTP {r["status"]} / error; not comparable'
                elif r["warmN"] != 20:
                    cell = f'incomplete: n={r["warmN"]}, expected 20'
                else:
                    cell = value(r)
                cells.append(cell)
            name = " / ".join(key).replace("|", "\\|").replace("\n", " ")
            print(f'| {name} | ' + " | ".join(cells) + " |")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pms-1k", type=Path, required=True)
    parser.add_argument("--ether-54k", type=Path)
    parser.add_argument("--ether-540k", type=Path)
    parser.add_argument("--ether-1-3m", type=Path)
    args = parser.parse_args()
    render([("PMS 1k", args.pms_1k), ("Ether 54k", args.ether_54k),
            ("Ether 540k", args.ether_540k), ("Ether 1.3M", args.ether_1_3m)])
